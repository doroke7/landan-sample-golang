package main

import (
	"fmt"
	"sync"
	"time"
)

/*

### 寫鎖 = 排它鎖 = Mutex = 普通鎖


### 🔒 普通鎖 (Mutex) 互斥權限矩陣

```text
                  【 A 用戶 (X軸) 】
                   ┌───────────────────┬───────────────────┐
                   │     👓 讀取       │     ✍️ 寫入         │
┌──────────────────┼───────────────────┼───────────────────┤
│                  │     ❌ 互斥       │     ❌ 互斥         │
│    👓 讀取       │                   │                    │
│                  │  (B在讀，A也要等)  │  (B在讀，A不能寫)    │
【 B 用戶 (Y軸) 】 ├───────────────────┼───────────────────┤
│                  │     ❌ 互斥       │     ❌ 互斥         │
│    ✍️ 寫入       │                   │                    │
│                  │  (B在寫，A不能讀)  │  (B在寫，A不能改)    │
└──────────────────┴───────────────────┴───────────────────┘



### ⚖️ 讀寫鎖 (RWMutex) 互斥權限矩陣

```text
                  【 A 用戶 (X軸) 】
                   ┌───────────────────┬───────────────────┐
                   │     👓 讀取        │     ✍️ 寫入        │
┌──────────────────┼───────────────────┼───────────────────┤
│                  │     🟢 允許         │     ❌ 互斥       │
│    👓 讀取        │                    │                  │
│                  │  (讀讀共享不排隊)    │  (B在讀，A不能寫)  │
│ 【 B 用戶 (Y軸) 】 ├───────────────────┼──────────────────┤
│                  │     ❌ 互斥        │     ❌ 互斥        │
│    ✍️ 寫入        │                   │                   │
│                  │  (B在寫，A不能讀)   │  (B在寫，A不能改)   │
└──────────────────┴───────────────────┴───────────────────┘

*/

func main() {
	var mu sync.RWMutex

	// 🟢 讀鎖：大家可以同時進來，不用排隊
	go func() {
		mu.RLock()
		fmt.Println("👓 讀者 A：正在看資料...")
		time.Sleep(1 * time.Second)
		mu.RUnlock()
	}()

	go func() {
		mu.RLock()
		fmt.Println("👓 讀者 B：我也在看資料，不用等 A 喔！")
		time.Sleep(1 * time.Second)
		mu.RUnlock()
	}()

	time.Sleep(100 * time.Millisecond) // 稍微等一下

	// 🔴 寫鎖：必須等上面的 A 和 B 都看完，他才能進去改
	go func() {
		mu.Lock()
		fmt.Println("✍️ 作者：大家都看完了，現在只有我能進來改資料！")
		mu.Unlock()
	}()

	time.Sleep(2 * time.Second) // 讓程式跑完
}
